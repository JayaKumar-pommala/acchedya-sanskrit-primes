"""Build SANSKRIT_VERSES.md: every Sanskrit passage the code uses, in depth.

All Sanskrit text, transliteration, numbers, metre scans and check results are
generated from corpus.py, vtools.py, check_verses.py and blocks.py, so the document
cannot drift from what the code verified. Glosses, translations and notes are
written here (own translations, not copied from any published translation).

Run:  python make_doc.py   -> writes SANSKRIT_VERSES.md
"""
