def anchor(line):
    m = re.match(r"## (\d+)\. ", line)
    return [f'<a id="s{m.group(1)}"></a>', ""] if m else []


def w(*lines):
    OUT.extend(lines)


def iast(s):
    return V.norm(s).replace("||", "॥").replace("|", "।") if False else V.norm(s)


def deva(s):
    return any("ऀ" <= ch <= "ॿ" for ch in s)


def checks(section, pred=lambda item: True):
    rows = [(ok, item, d) for s, item, ok, d in RES if s == section and pred(item)]
    if not rows:
        return
    w("", "| | Check | Result |", "|---|---|---|")
    for ok, item, d in rows:
        mark = "✓" if ok is True else ("✗" if ok is False else "—")
        w(f"| {mark} | {item} | {str(d).replace('|', '/')} |")
    w("")


def text_block(lines, label_deva="Devanāgarī (as retrieved)", label_iast="IAST"):
    """Show Devanagari if the source has it, and IAST always."""
    if any(deva(l) for l in lines):
        w(f"**{label_deva}**", "", "```text", *lines, "```", "")
    w(f"**{label_iast}**" + ("" if any(deva(l) for l in lines) else " (as retrieved; no Devanāgarī in the source used)"),
      "", "```text", *[V.norm(l) for l in lines], "```", "")


def gloss(rows):
    w("**Key terms**", "", "| Term | Meaning here |", "|---|---|")
    for t, m in rows:
        w(f"| *{t}* | {m} |")
    w("")


def meta(d, role=None):
    st = {"sanskrit": "Sanskrit retrieved", "sanskrit-frag": "Sanskrit fragment only",
          "scan-reading": "scan reading, not collated", "ocr-reading": "OCR of the printed edition, restored by us", "translation": "translation only"}[d["status"]]
    src = C.SRC.get(d["src"], d["src"])
    w(f"- **Status:** {st}", f"- **Source:** {src}")
    if d.get("metre"):
        w(f"- **Metre:** {d['metre']}")
    if role:
        w(f"- **Used in code:** {role}")
    w("")


def metre_table(results, kind):
    w(f"**Metre scan ({kind})** — `–` heavy, `⏑` light", "", "| Line | Pattern | Count | OK |", "|---|---|---|---|")
    for i, r in enumerate(results, 1):
        cnt = r.get("matras", r.get("syllables", ""))
        if "expected" in r:
            cnt = f"{cnt} / {r['expected']} mātrās"
        elif "padas" in r:
            cnt = " + ".join(r["padas"])
        w(f"| {i} | `{r['pattern']}` | {cnt} | {'✓' if r['ok'] else '✗'} |")
    w("")


