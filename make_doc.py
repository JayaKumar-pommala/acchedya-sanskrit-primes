  "re-joined by sandhi (`vtools.join_all`) and compared with the written text, so the split is tested, not assumed.", "",
  "### 3.5 Arithmetic chains", "",
  "Where a text gives numbers that depend on each other (Sūrya Siddhānta 1.29–37, the yuga verses), the checker "
